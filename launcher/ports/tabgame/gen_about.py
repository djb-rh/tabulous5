#!/usr/bin/env python3
"""gen_about.py NAME OUT.h: one game's name, strapline, colour, mark and About text, taken from the table in
the console's own shell (src/app.cpp) so the wording lives in one place."""
import os, re, sys
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "src", "app.cpp")).read()
S = r'"(?:[^"\\]|\\.)*"'
pat = re.compile(r'\{\s*(' + S + r')\s*,\s*((?:' + S + r'\s*)+),\s*(0x[0-9A-Fa-f]+)\s*,\s*glyphs::Glyph::(\w+)\s*,\s*GameId::(\w+)\s*,\s*((?:' + S + r'\s*)+)\}', re.S)
want = sys.argv[1]
for m in pat.finditer(src):
    if m.group(1).strip('"') == want:
        # as a launcher app the button that leaves says EXIT (APP_LEAVE_LABEL), so the About text must too
        about = re.sub(r'\bMENU\b', 'EXIT', m.group(6).rstrip())
        open(sys.argv[2], "w").write(
            "// Generated by gen_about.py from tabulous5/src/app.cpp. Do not edit.\n"
            "#define ABOUT_NAME %s\n#define ABOUT_BLURB %s\n#define ABOUT_COLOR %s\n#define ABOUT_GLYPH tabulous::glyphs::Glyph::%s\n"
            "static const char kAboutText[] =\n%s;\n" % (m.group(1), " ".join(m.group(2).split("\n")), m.group(3), m.group(4), about))
        sys.exit(0)
sys.exit("no entry named %r in app.cpp" % want)
