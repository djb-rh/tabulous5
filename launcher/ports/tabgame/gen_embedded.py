#!/usr/bin/env python3
"""gen_embedded.py OUT.c [packs]: the files a game carries inside itself, as C: the console's seven sound samples
(data/sfx), and with `packs` its word packs too (data/packs). The Store installs an app as one file, so an app
shared there cannot count on anything being on the card; m5compat's LittleFS looks on the card first and here
second (ports/m5compat/include/LittleFS.h)."""
import glob, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
files = [("/sfx/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(ROOT, "data", "sfx", "*.wav")))]
if "packs" in sys.argv[2:]:
    files += [("/packs/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(ROOT, "data", "packs", "*.txt")))]
out = ["/* Generated by gen_embedded.py from data/sfx and data/packs. Do not edit. */",
       "typedef struct { const char *path; const unsigned char *data; unsigned size; } m5compat_embedded_t;"]
for i, (name, path) in enumerate(files):
    d = open(path, "rb").read()
    out.append("static const unsigned char f%d[%d] = {" % (i, len(d)))
    out += ["  " + ",".join(str(b) for b in d[k:k + 32]) + "," for k in range(0, len(d), 32)]
    out.append("};")
out.append("static const m5compat_embedded_t files[] = {")
out += ['  {"%s", f%d, sizeof f%d},' % (name, i, i) for i, (name, _) in enumerate(files)]
out.append("};")
out.append("const m5compat_embedded_t *m5compat_embedded(int *count) { *count = %d; return files; }" % len(files))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("embedded: %d files, %d bytes" % (len(files), sum(os.path.getsize(p) for _, p in files)))
